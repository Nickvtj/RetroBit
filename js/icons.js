const CURSOR_COLORS = { K: '#000', W: '#fff', R: '#ff3b30', Y: '#ffd23f', O: '#ff8a00', C: '#0bd3d3' };

/** Nomes dos cursores pixel-art → variável CSS `--cur-<nome>` (definidas em ui.js). */
export const CURSOR_NAMES = Object.keys(CURSOR_ART);

/** Valor CSS `cursor:` para um cursor pixel-art (com recurso ao cursor do sistema). */
export function cursorCss(name, fallback = 'auto') {
  const { rows, hot } = CURSOR_ART[name];
  let rects = '';
  rows.forEach((row, y) => [...row].forEach((ch, x) => {
    if (CURSOR_COLORS[ch]) rects += `<rect x="${x}" y="${y}" width="1" height="1" fill="${CURSOR_COLORS[ch]}"/>`;
  }));
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="32" height="32" viewBox="0 0 16 16" shape-rendering="crispEdges">${rects}</svg>`;
  return `url("data:image/svg+xml,${encodeURIComponent(svg)}") ${hot[0] * 2} ${hot[1] * 2}, ${fallback}`;
}
