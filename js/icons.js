const flipH = (rows) => rows.map((r) => [...r].reverse().join(''));
const transpose = (rows) => rows[0].split('').map((_, x) => rows.map((r) => r[x]).join(''));

ART.redo = flipH(ART.undo);
ART.right = flipH(ART.left);
ART.mirrorV = transpose(ART.mirrorH);

/** Uma faixa horizontal de pixels acesos vira um retângulo do path. */
function toPath(rows) {
  let d = '';
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length;) {
      if (row[x] !== '#') { x++; continue; }
      let end = x;
      while (row[end] === '#') end++;
      d += `M${x} ${y}h${end - x}v1h${x - end}z`;
      x = end;
    }
  });
  return d;
}

const cache = new Map();

/** SVG do ícone `name` (string). Ícone desconhecido → string vazia. */
export function icon(name) {
  if (!ART[name]) return '';
  if (!cache.has(name)) {
    const rows = ART[name];
    cache.set(name, `<svg class="px-icon" viewBox="0 0 ${rows[0].length} ${rows.length}" `
      + `shape-rendering="crispEdges" aria-hidden="true" focusable="false">`
      + `<path fill="currentColor" d="${toPath(rows)}"/></svg>`);
  }
  return cache.get(name);
}

/** Troca cada <i data-icon="nome"> dentro de `root` pelo SVG correspondente. */
export function hydrateIcons(root = document) {
  root.querySelectorAll('i[data-icon]').forEach((el) => {
    el.outerHTML = icon(el.dataset.icon);
  });
}

